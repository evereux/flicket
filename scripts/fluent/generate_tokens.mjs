// Writes the Fluent theme tokens as static CSS custom properties, so the app
// does not need setTheme() at runtime and first paint already has colours.
//
// Usage, from the repository root:
//   node scripts/fluent/generate_tokens.mjs <dir containing @fluentui/tokens> > application/flicket/static/css/fluent-tokens.css
//
// The pinned package can be installed into a scratch directory first:
//   npm install --prefix /tmp/fluent-vendor @fluentui/tokens@1.0.0-alpha.24
import { readFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

const packageDir = process.argv[2];
if (!packageDir) {
  console.error('usage: node scripts/fluent/generate_tokens.mjs <dir containing @fluentui/tokens>');
  process.exit(1);
}

const tokensRoot = resolve(packageDir, '@fluentui', 'tokens');
const { version } = JSON.parse(readFileSync(join(tokensRoot, 'package.json'), 'utf8'));
const { webLightTheme, webDarkTheme } = await import(pathToFileURL(join(tokensRoot, 'lib', 'index.js')).href);

// Same rules the web components apply when they set tokens at runtime.
const TOKEN_NAME = /^[a-zA-Z_-][a-zA-Z0-9_-]*$/;
const UNSAFE_VALUE = /(;|{|}|\/\*|\*\/|@import|url\s*\(|expression\s*\(|javascript:)/i;

function readTheme(theme) {
  const tokens = new Map();
  for (const [name, raw] of Object.entries(theme)) {
    const value = String(raw);
    if (!TOKEN_NAME.test(name) || UNSAFE_VALUE.test(value)) {
      console.error(`skipped token "${name}"`);
      continue;
    }
    tokens.set(name, value);
  }
  return tokens;
}

const light = readTheme(webLightTheme);
const dark = readTheme(webDarkTheme);

const declaration = ([name, value]) => `  --${name}: ${value};`;
const lightBlock = [...light].map(declaration).join('\n');
const darkBlock = [...dark]
  .filter(([name, value]) => light.get(name) !== value)
  .map(declaration)
  .join('\n');

process.stdout.write(`/* Generated by scripts/fluent/generate_tokens.mjs from @fluentui/tokens ${version}. Do not edit by hand. */

:root,
[data-theme="light"] {
  color-scheme: light;
${lightBlock}
}

[data-theme="dark"] {
  color-scheme: dark;
${darkBlock}
}
`);
